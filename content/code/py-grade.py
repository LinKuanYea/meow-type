期中考, 期末考, 作業 = input().split()
期中考 = int(期中考)
期末考 = int(期末考)
作業 = int(作業)
學期總分 = 期中考*0.25 + 期末考*0.30 + 作業*0.45

if 學期總分 % 1 == 0:
    學期總分 = int(學期總分)
print(f'總分：{學期總分}。', end='')

if 學期總分 < 40:
    print('死當QQ')

elif 學期總分 < 60:
    print('可以補考！')

elif 學期總分 < 70:
    print('低空飛過><')

elif 學期總分 >= 90:
    print('簡直是神。')

else:
    print('過了～')
